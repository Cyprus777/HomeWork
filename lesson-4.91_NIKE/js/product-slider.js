const productSlider = () => {
	//объявляет и экспортирует функцию с именем productSlider, которую можно импортировать в другие файлы проекта.
	new Swiper(".product__slider", {
		//создает новый экземпляр слайдера Swiper, привязывая его к HTML-элементу с классом .product__slider
		slidesPerView: "auto", //указывает слайдеру автоматически определять количество отображаемых слайдов на основе их ширины в CSS.
		centeredSlides: true, //включает режим центрирования активного слайда (он всегда будет находиться посередине области просмотра).
		loop: true, // включает режим бесконечной прокрутки слайдов.
		mousewheel: {
			// активирует возможность прокрутки слайдов с помощью колесика мыши.
			forceToAxis: true, // ограничивает прокрутку только по оси слайдера (горизонтально), предотвращая прокрутку всей страницы.
		}, // завершает объект настроек для управления колесиком мыши.
		spaceBetween: 90, // Отступ между слайдами (в пикселях)
		navigation: {
			// объект для настройки кнопок навигации (стрелок вперед/назад).
			prevEl: ".product__slider-button--prev", // указывает селектор элемента, который будет выполнять функцию кнопки "назад".
			nextEl: ".product__slider-button--next", // указывает селектор элемента, который будет выполнять функцию кнопки "вперед".
		},
	}); //закрывает объект настроек и конструктор класса Swiper.
}; //завершает тело функции.

productSlider()
